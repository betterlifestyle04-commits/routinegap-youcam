import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {evaluateShop,sampleShelf,sampleScan} from '../src/recommendations.js';

test('guided demo is explicitly sample-only and has a complete navigable four-step path',async()=>{
 const app=await readFile(new URL('../public/app.js',import.meta.url),'utf8');
 for(const needle of ['THE 60-SECOND JUDGE WALKTHROUGH','id="guided-demo"','id="demo-step-scan"','data-go="shelf"','data-go="shop"','data-go="trail"','demo is not evidence of a completed live scan'])assert.ok(app.includes(needle),needle);
 assert.match(app,/if\(event\.target\.closest\('#guided-demo'\).*return setSample\(\)/);
 assert.match(app,/state\.scan=sampleScan\.map/);
 assert.match(app,/Illustrative sample loaded.*not generated by the YouCam API/);
});
test('overview spending shows actual selected demo cart rather than an automatic suggestion',async()=>{
 const app=await readFile(new URL('../public/app.js',import.meta.url),'utf8');
 assert.match(app,/const selectedCart=d\.rows\.filter\(x=>state\.cartIds\.includes\(x\.id\)\)/);
 assert.match(app,/selectedTotal=selectedCart\.reduce/);
 assert.match(app,/Your selected demo cart/);
 assert.match(app,/selectedTotal>d\.budget\?'Over budget by '/);
 const d=evaluateShop({shelf:sampleShelf,budget:20,goal:'moisture'});
 const chosen=d.rows.filter(x=>['mineral-spf'].includes(x.id));
 assert.equal(chosen.reduce((total,item)=>total+item.price,0),23);
 assert.equal(d.cartTotal,0);
 assert.ok(chosen[0].price>d.budget);
});
test('demo walk-through includes accessible buttons and responsive layouts',async()=>{
 const css=await readFile(new URL('../public/styles.css',import.meta.url),'utf8');
 assert.match(css,/demo-journey-steps button:focus-visible/);
 assert.match(css,/@media\(max-width:540px\)/);
 assert.equal(sampleScan.length>0,true);
});
